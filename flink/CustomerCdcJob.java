package com.customerplatform;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import org.apache.flink.api.common.eventtime.WatermarkStrategy;
import org.apache.flink.api.common.serialization.SimpleStringSchema;
import org.apache.flink.connector.kafka.source.KafkaSource;
import org.apache.flink.connector.kafka.source.enumerator.initializer.OffsetsInitializer;
import org.apache.flink.streaming.api.environment.StreamExecutionEnvironment;
import org.apache.flink.streaming.api.functions.sink.legacy.RichSinkFunction;

import java.sql.Connection;
import java.sql.Date;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.Timestamp;
import java.time.Instant;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.OffsetDateTime;
import java.util.Objects;

/**
 * Consumes Debezium events for staging.stg_customers and maintains
 * business.dim_customer as an SCD Type 2 dimension.
 *
 * Type 2 attributes: segment, address.
 * Type 1 attributes: first_name, last_name, email, phone, city, country,
 *                   birthdate, source_system.
 *
 * Assumes customer_id is the natural key in the dimension and that
 * customer_sk is generated by PostgreSQL.
 */
public class CustomerCdcJob {

    public static void main(String[] args) throws Exception {
        StreamExecutionEnvironment env =
                StreamExecutionEnvironment.getExecutionEnvironment();
        env.enableCheckpointing(10_000);

        KafkaSource<String> source = KafkaSource.<String>builder()
                .setBootstrapServers(System.getenv().getOrDefault(
                        "KAFKA_BOOTSTRAP_SERVERS", "kafka:9092"))
                .setTopics(System.getenv().getOrDefault(
                        "KAFKA_TOPIC", "customer.staging.stg_customers"))
                .setGroupId(System.getenv().getOrDefault(
                        "KAFKA_GROUP_ID", "customer-business-job"))
                // Use earliest for the first run so existing snapshot events
                // can populate the dimension. Kafka remembers offsets afterward.
                .setStartingOffsets(OffsetsInitializer.earliest())
                .setValueOnlyDeserializer(new SimpleStringSchema())
                .build();

        env.fromSource(source, WatermarkStrategy.noWatermarks(), "customer-staging-cdc-source")
                .addSink(new CustomerDimensionSink())
                .name("maintain-customer-dimension-scd2")
                .uid("maintain-customer-dimension-scd2")
                .setParallelism(1);

        env.execute("Customer CDC Business Dimension");
    }

    private static final class CustomerDimensionSink extends RichSinkFunction<String> {
        private transient Connection connection;
        private transient ObjectMapper mapper;
        private transient PreparedStatement selectCurrent;
        private transient PreparedStatement insertDimension;
        private transient PreparedStatement updateType1;
        private transient PreparedStatement closeCurrent;
        private transient PreparedStatement findOtherValidStagingRow;

        @Override
        public void open(org.apache.flink.api.common.functions.OpenContext openContext)
                throws Exception {
            mapper = new ObjectMapper();
            String host = System.getenv().getOrDefault("POSTGRES_HOST", "postgres");
            String port = System.getenv().getOrDefault("POSTGRES_PORT", "5432");
            String db = System.getenv().getOrDefault("POSTGRES_DB", "appdb");
            String user = System.getenv().getOrDefault("POSTGRES_USER", "postgres");
            String password = System.getenv("POSTGRES_PASSWORD");
            if (password == null || password.isBlank()) {
                throw new IllegalStateException(
                        "POSTGRES_PASSWORD environment variable is required by the Flink job");
            }

            connection = DriverManager.getConnection(
                    "jdbc:postgresql://" + host + ":" + port + "/" + db,
                    user,
                    password);
            connection.setAutoCommit(false);

            selectCurrent = connection.prepareStatement(
                    "SELECT customer_sk, segment, address, valid_from " +
                    "FROM business.dim_customer " +
                    "WHERE customer_id = ? AND is_current = TRUE " +
                    "ORDER BY valid_from DESC LIMIT 1 FOR UPDATE");

            insertDimension = connection.prepareStatement(
                    "INSERT INTO business.dim_customer (" +
                    "customer_id, first_name, last_name, email, phone, address, city, country, " +
                    "segment, birthdate, source_system, valid_from, valid_to, is_current, " +
                    "created_at, updated_at) " +
                    "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, NULL, TRUE, ?, ?)");

            // Type 1 changes are reflected in all historical versions too.
            updateType1 = connection.prepareStatement(
                    "UPDATE business.dim_customer SET " +
                    "first_name = ?, last_name = ?, email = ?, phone = ?, city = ?, country = ?, " +
                    "birthdate = ?, source_system = ?, updated_at = ? " +
                    "WHERE customer_id = ?");

            closeCurrent = connection.prepareStatement(
                    "UPDATE business.dim_customer " +
                    "SET valid_to = ?, is_current = FALSE " +
                    "WHERE customer_sk = ? AND is_current = TRUE");

            findOtherValidStagingRow = connection.prepareStatement(
                    "SELECT 1 FROM staging.stg_customers " +
                    "WHERE customer_id = ? AND is_valid = TRUE LIMIT 1");
        }

        @Override
        public void invoke(String message, Context context) throws Exception {
            JsonNode root = mapper.readTree(message);
            JsonNode payload = root.path("payload");
            if (payload.isMissingNode() || payload.isNull()) {
                // Ignore tombstones and malformed/non-envelope messages.
                return;
            }

            String operation = payload.path("op").asText("");
            JsonNode after = payload.path("after");
            JsonNode before = payload.path("before");
            JsonNode row = ("d".equals(operation)) ? before : after;
            String customerId = textOrNull(row.path("customer_id"));
            if (customerId == null) {
                return;
            }

            Timestamp eventTime = eventTimestamp(payload, after);

            try {
                if ("d".equals(operation)) {
                    handleDelete(customerId, eventTime);
                    connection.commit();
                    return;
                }

                // Debezium op values: c=create, u=update, r=read/snapshot.
                if (!("c".equals(operation) || "u".equals(operation) || "r".equals(operation))
                        || after.isMissingNode() || after.isNull()) {
                    connection.commit();
                    return;
                }

                // Do not let rejected staging records enter the business dimension.
                JsonNode validNode = after.path("is_valid");
                if (!validNode.isMissingNode() && !validNode.isNull()
                        && !validNode.asBoolean(false)) {
                    connection.commit();
                    return;
                }

                if (eventTime == null) {
                    eventTime = Timestamp.from(Instant.now());
                }

                String segment = textOrNull(after.path("segment"));
                String address = textOrNull(after.path("address"));

                selectCurrent.setString(1, customerId);
                long currentSk = -1;
                Timestamp validFrom = null;
                String currentSegment = null;
                String currentAddress = null;
                try (ResultSet rs = selectCurrent.executeQuery()) {
                    if (rs.next()) {
                        currentSk = rs.getLong("customer_sk");
                        validFrom = rs.getTimestamp("valid_from");
                        currentSegment = rs.getString("segment");
                        currentAddress = rs.getString("address");
                    }
                }

                if (currentSk == -1) {
                    insertNewCustomer(after, customerId, eventTime);
                    connection.commit();
                    System.out.println("Inserted new dimension customer " + customerId);
                    return;
                }

                boolean type2Changed = !Objects.equals(currentSegment, segment)
                        || !Objects.equals(currentAddress, address);

                // Replayed/old events should not create duplicate versions.
                if (validFrom != null && eventTime.before(validFrom)) {
                    connection.commit();
                    return;
                }

                if (type2Changed) {
                    // Ensure two rapid changes do not create zero-length versions
                    // when the source timestamps have only millisecond precision.
                    if (validFrom != null && !eventTime.after(validFrom)) {
                        eventTime = new Timestamp(validFrom.getTime() + 1);
                    }
                    closeCurrent.setTimestamp(1, eventTime);
                    closeCurrent.setLong(2, currentSk);
                    closeCurrent.executeUpdate();
                    insertNewCustomer(after, customerId, eventTime);
                    updateType1Attributes(after, customerId, eventTime);
                    connection.commit();
                    System.out.println("Customer " + customerId
                            + ": SCD2 version created (segment/address changed)");
                } else {
                    // Email/name/phone/city/country/birthdate/source-system changes
                    // update Type 1 attributes without creating a new SCD2 version.
                    updateType1Attributes(after, customerId, eventTime);
                    connection.commit();
                }
            } catch (Exception e) {
                connection.rollback();
                throw e;
            }
        }

        private void insertNewCustomer(JsonNode row, String customerId, Timestamp eventTime)
                throws Exception {
            insertDimension.setString(1, customerId);
            insertDimension.setString(2, textOrNull(row.path("first_name")));
            insertDimension.setString(3, textOrNull(row.path("last_name")));
            insertDimension.setString(4, textOrNull(row.path("email")));
            insertDimension.setString(5, textOrNull(row.path("phone")));
            insertDimension.setString(6, textOrNull(row.path("address")));
            insertDimension.setString(7, textOrNull(row.path("city")));
            insertDimension.setString(8, textOrNull(row.path("country")));
            insertDimension.setString(9, textOrNull(row.path("segment")));
            insertDimension.setDate(10, dateValue(row.path("birthdate")));
            insertDimension.setString(11, textOrNull(row.path("source_system")));
            insertDimension.setTimestamp(12, eventTime);
            insertDimension.setTimestamp(13, timestampField(row.path("created_at"), eventTime));
            insertDimension.setTimestamp(14, eventTime);
            insertDimension.executeUpdate();
        }

        private void updateType1Attributes(JsonNode row, String customerId, Timestamp eventTime)
                throws Exception {
            updateType1.setString(1, textOrNull(row.path("first_name")));
            updateType1.setString(2, textOrNull(row.path("last_name")));
            updateType1.setString(3, textOrNull(row.path("email")));
            updateType1.setString(4, textOrNull(row.path("phone")));
            updateType1.setString(5, textOrNull(row.path("city")));
            updateType1.setString(6, textOrNull(row.path("country")));
            updateType1.setDate(7, dateValue(row.path("birthdate")));
            updateType1.setString(8, textOrNull(row.path("source_system")));
            updateType1.setTimestamp(9, eventTime);
            updateType1.setString(10, customerId);
            updateType1.executeUpdate();
        }

        private void handleDelete(String customerId, Timestamp eventTime) throws Exception {
            // If another valid staging row still represents this customer, keep
            // the dimension active. A raw-record delete is not always a customer delete.
            findOtherValidStagingRow.setString(1, customerId);
            try (ResultSet other = findOtherValidStagingRow.executeQuery()) {
                if (other.next()) {
                    return;
                }
            }

            selectCurrent.setString(1, customerId);
            long customerSk;
            Timestamp validFrom;
            try (ResultSet current = selectCurrent.executeQuery()) {
                if (!current.next()) {
                    return;
                }
                customerSk = current.getLong("customer_sk");
                validFrom = current.getTimestamp("valid_from");
            }
            if (eventTime == null) {
                eventTime = Timestamp.from(Instant.now());
            }
            if (validFrom != null && !eventTime.after(validFrom)) {
                eventTime = new Timestamp(validFrom.getTime() + 1);
            }
            closeCurrent.setTimestamp(1, eventTime);
            closeCurrent.setLong(2, customerSk);
            closeCurrent.executeUpdate();
        }

        private Timestamp eventTimestamp(JsonNode payload, JsonNode after) {
            // Debezium payload.ts_ms is milliseconds since epoch and is preferred
            // as the CDC event time. Staging updated_at may be MicroTimestamp (µs).
            JsonNode tsMs = payload.path("ts_ms");
            if (tsMs.isNumber()) {
                return new Timestamp(tsMs.asLong());
            }
            return timestampField(after.path("updated_at"), null);
        }

        private Timestamp timestampField(JsonNode value, Timestamp fallback) {
            if (value == null || value.isMissingNode() || value.isNull()) {
                return fallback;
            }
            if (value.isNumber()) {
                // PostgreSQL Debezium MicroTimestamp values are epoch microseconds.
                return new Timestamp(value.asLong() / 1_000L);
            }
            if (!value.isTextual() || value.asText().isBlank()) {
                return fallback;
            }
            String text = value.asText().trim();
            try {
                return new Timestamp(Long.parseLong(text) / 1_000L);
            } catch (NumberFormatException ignored) {
                try {
                    return Timestamp.valueOf(LocalDateTime.parse(text));
                } catch (Exception ignoredLocal) {
                    try {
                        return Timestamp.from(Instant.parse(text));
                    } catch (Exception ignoredInstant) {
                        try {
                            return Timestamp.from(OffsetDateTime.parse(text).toInstant());
                        } catch (Exception ignoredOffset) {
                            return fallback;
                        }
                    }
                }
            }
        }

        private Date dateValue(JsonNode value) {
            if (value == null || value.isMissingNode() || value.isNull()
                    || value.asText().isBlank()) {
                return null;
            }
            if (value.isNumber()) {
                // Debezium DATE logical values are days since 1970-01-01.
                return Date.valueOf(LocalDate.ofEpochDay(value.asLong()));
            }
            try {
                return Date.valueOf(value.asText());
            } catch (IllegalArgumentException e) {
                return null;
            }
        }

        private String textOrNull(JsonNode node) {
            if (node == null || node.isMissingNode() || node.isNull()) {
                return null;
            }
            String value = node.asText();
            return value == null || value.isBlank() ? null : value;
        }

        @Override
        public void close() throws Exception {
            if (findOtherValidStagingRow != null) findOtherValidStagingRow.close();
            if (closeCurrent != null) closeCurrent.close();
            if (updateType1 != null) updateType1.close();
            if (insertDimension != null) insertDimension.close();
            if (selectCurrent != null) selectCurrent.close();
            if (connection != null) connection.close();
        }
    }
}
